#!/usr/bin/env bash
# Scrape the agent's own environment into self/inventory.md.
# Deterministic output (no timestamps in the body) so `git diff` shows only real changes.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/self/inventory.md"
CLAUDE_HOME="${CLAUDE_HOME:-$HOME/.claude}"
mkdir -p "$ROOT/self"

skill_line() { # path/to/SKILL.md -> "- name: description"
  local f="$1" name desc
  name=$(sed -n 's/^name:[[:space:]]*//p' "$f" | head -1 | tr -d '"')
  desc=$(sed -n 's/^description:[[:space:]]*//p' "$f" | head -1 | sed 's/\\n.*//; s/\\"//g; s/"//g' | cut -c1-140)
  echo "- \`${name:-$(basename "$(dirname "$f")")}\`: ${desc}"
}

missing=()
{
  echo "# Self inventory"
  echo
  echo "_Generated by \`scripts/scrape_self.sh\`. Do not edit by hand; rerun the script._"
  echo
  echo "## Runtime"
  echo "- Claude Code: $(claude --version 2>/dev/null | head -1 || echo unknown)"
  echo "- OS: $(uname -sr)"
  echo "- Remote session: $([ -n "${CLAUDE_CODE_REMOTE:-}" ] && echo yes || echo unknown)"
  echo "- HolyClaude container: $([ -f "$HOME/.claude/.holyclaude-bootstrapped" ] && echo yes || echo no)"
  echo
  echo "## CLI tools on PATH"
  # list mirrors HolyClaude's toolset so the inventory shows what's missing vs. a full workstation
  for t in git gh gcloud bq node npm pnpm tsc vite python3 pip uv go cargo rustc docker rg fdfind fzf jq yq curl wget \
           ffmpeg pandoc convert vips sqlite3 psql redis-cli chromium firecrawl playwright yt-dlp soffice \
           gemini codex cursor opencode task-master vercel wrangler netlify desloppify; do
    if command -v "$t" >/dev/null 2>&1; then echo "- \`$t\`"; else missing+=("$t"); fi
  done
  echo
  echo "Missing: ${missing[*]:-none}"
  echo
  echo "## Plugins (synced)"
  for m in "$CLAUDE_HOME"/plugins/synced/*/manifest.json; do
    [ -f "$m" ] || continue
    jq -r '.plugins[] | "- v\(.version): \(.description)"' "$m" 2>/dev/null | sort
  done
  echo
  echo "## Plugin skills"
  find "$CLAUDE_HOME/plugins/synced" -path '*/skills/*/SKILL.md' 2>/dev/null | sort | while read -r f; do skill_line "$f"; done
  echo
  echo "## User skills (~/.claude/skills)"
  find "$CLAUDE_HOME/skills" -maxdepth 2 -name SKILL.md 2>/dev/null | sort | while read -r f; do skill_line "$f"; done
  echo
  echo "## Project skills (.claude/skills)"
  find "$ROOT/.claude/skills" -maxdepth 2 -name SKILL.md 2>/dev/null | sort | while read -r f; do skill_line "$f"; done
  echo
  echo "## Project agents (.claude/agents)"
  find "$ROOT/.claude/agents" -name '*.md' 2>/dev/null | sort | sed 's|.*/||; s|\.md$||; s|^|- |'
  echo
  echo "## Catalog (on-demand, not auto-loaded)"
  if [ -f "$ROOT/catalog/INDEX.tsv" ]; then
    tail -n +2 "$ROOT/catalog/INDEX.tsv" | cut -f1,2 | sort | uniq -c | awk '{print "- " $3 " " $2 "s: " $1}'
    echo "- search: python3 scripts/catalog.py search <terms>"
  else
    echo "- Composio app playbooks: $(find "$ROOT/catalog/composio" -name '*.md' ! -name INDEX.md 2>/dev/null | wc -l | tr -d ' ') (use /app-automation)"
    echo "- Full catalog not imported yet (python3 scripts/import_sources.py)"
  fi
  echo
  echo "## MCP servers declared by plugins"
  find "$CLAUDE_HOME/plugins/synced" -name .mcp.json 2>/dev/null | sort | while read -r f; do
    jq -r '(.mcpServers // .) | keys[] | "- `\(.)`"' "$f" 2>/dev/null
  done
} > "$OUT"

echo "wrote $OUT"
