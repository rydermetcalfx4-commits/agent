#!/usr/bin/env bash
# Scrape upstream sources (sources.txt) and integrate them into this repo.
# Re-runnable: each run replaces vendored copies with the latest upstream.
#   bash scripts/import_sources.sh            # clone fresh into a temp dir
#   SRC_DIR=/path/with/clones bash scripts/import_sources.sh   # reuse existing clones
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC_DIR="${SRC_DIR:-$(mktemp -d)}"
SKILLS="$ROOT/.claude/skills"
CATALOG="$ROOT/catalog"

clone() { # url dir
  [ -d "$SRC_DIR/$2/.git" ] || git clone -q --depth 1 "$1" "$SRC_DIR/$2"
  git -C "$SRC_DIR/$2" log -1 --format="%H" > "$SRC_DIR/$2.rev"
}
clone https://github.com/ComposioHQ/awesome-claude-skills awesome-claude-skills
clone https://github.com/CoderLuii/HolyClaude HolyClaude
ACS="$SRC_DIR/awesome-claude-skills"
HC="$SRC_DIR/HolyClaude"

# ---- awesome-claude-skills: standalone skills -> .claude/skills/ ----------
# Skipped on purpose:
#   document-skills  proprietary Anthropic license; built-in anthropic-skills:{docx,pdf,pptx,xlsx} cover it
#   skill-creator    duplicate of built-in anthropic-skills:skill-creator
#   template-skill   a template, kept in catalog/ instead
#   connect, connect-apps, connect-apps-plugin, composio-skills  folded into the app-automation router
SKIP=" document-skills skill-creator template-skill connect connect-apps connect-apps-plugin composio-skills "
imported=()
for d in "$ACS"/*/; do
  name=$(basename "$d")
  [[ "$SKIP" == *" $name "* ]] && continue
  [ -f "$d/SKILL.md" ] || continue
  rm -rf "${SKILLS:?}/$name"
  cp -r "$d" "$SKILLS/$name"
  imported+=("$name")
done
mkdir -p "$CATALOG/templates"
cp "$ACS/template-skill/SKILL.md" "$CATALOG/templates/SKILL.template.md"

# ---- composio-skills: 800+ app wrappers -> catalog (not auto-loaded) -------
rm -rf "$CATALOG/composio"
mkdir -p "$CATALOG/composio"
for f in "$ACS"/composio-skills/*/SKILL.md; do
  app=$(basename "$(dirname "$f")" | sed 's/^-*//; s/-automation$//')
  cp "$f" "$CATALOG/composio/$app.md"
done
{
  echo "# Composio app index"
  echo
  echo "One file per app in this folder. Each needs the Rube MCP server (see .claude/skills/app-automation)."
  echo
  for f in "$CATALOG"/composio/*.md; do
    [ "$(basename "$f")" = INDEX.md ] && continue
    echo "- $(basename "$f" .md)"
  done
} > "$CATALOG/composio/INDEX.md"

# ---- awesome-claude-skills README: index of external skills ---------------
{
  echo "# External skill index (from awesome-claude-skills README)"
  echo
  echo "Not vendored: these live in other repos. Install one when a task needs it, then run /evolve."
  echo
  awk '/^## Skills/{on=1} /^## Getting Started/{on=0} on && (/^### / || /^- \[/)' "$ACS/README.md" \
    | grep -v '](\./' | sed 's/^### /\n## /'
} > "$CATALOG/external-skills.md"

# ---- HolyClaude: container runtime + notification hook --------------------
mkdir -p "$ROOT/holyclaude"
cp "$HC/scripts/notify.py" "$ROOT/scripts/notify.py"
# upstream hardcodes the container user's home; make it work for any user
sed -i 's|^FLAG_FILE = "/home/claude/.claude/notify-on"|FLAG_FILE = os.path.expanduser("~/.claude/notify-on")|' "$ROOT/scripts/notify.py"
cp "$HC/config/claude-memory-full.md" "$ROOT/holyclaude/environment-full.md"
cp "$HC/config/claude-memory-slim.md" "$ROOT/holyclaude/environment-slim.md"
cp "$HC/LICENSE" "$ROOT/holyclaude/LICENSE"

# ---- provenance -----------------------------------------------------------
{
  echo "# Third-party sources"
  echo
  echo "Generated by \`scripts/import_sources.sh\`."
  echo
  echo "| Source | Commit | License | Where it went |"
  echo "|---|---|---|---|"
  echo "| [ComposioHQ/awesome-claude-skills](https://github.com/ComposioHQ/awesome-claude-skills) | \`$(cut -c1-12 "$SRC_DIR/awesome-claude-skills.rev")\` | Apache-2.0 (per-skill LICENSE.txt where present) | \`.claude/skills/\` (${#imported[@]} skills), \`catalog/\` |"
  echo "| [CoderLuii/HolyClaude](https://github.com/CoderLuii/HolyClaude) | \`$(cut -c1-12 "$SRC_DIR/HolyClaude.rev")\` | MIT (\`holyclaude/LICENSE\`) | \`holyclaude/\`, \`scripts/notify.py\` |"
  echo
  echo "Imported skills: $(printf '`%s` ' "${imported[@]}")"
} > "$ROOT/THIRD_PARTY.md"

echo "imported ${#imported[@]} skills, $(ls "$CATALOG/composio" | wc -l) catalog files"
